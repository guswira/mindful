#!/usr/bin/env python3
"""Writes lib/core/l10n/date_symbols_subset.dart: intl's date symbols and
patterns for only the app's locales (en, en_US, id).

intl's initializeDateFormatting() (date_symbol_data_local.dart) bundles the
data for every locale it knows, ~565 KB of Dart source that the web build
ships in full. Re-run after upgrading intl:

    python3 tool/gen_date_symbols.py && dart format lib/core/l10n
"""

import json
import pathlib
import re
import urllib.parse

LOCALES = ["en", "en_US", "id"]
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "lib/core/l10n/date_symbols_subset.dart"


def intl_lib() -> tuple[pathlib.Path, str]:
    config = json.loads((ROOT / ".dart_tool/package_config.json").read_text())
    for package in config["packages"]:
        if package["name"] == "intl":
            root = urllib.parse.unquote(package["rootUri"].replace("file://", ""))
            version = re.search(r"intl-([\d.]+)", root)
            return pathlib.Path(root) / "lib", version.group(1) if version else "?"
    raise SystemExit("intl not found — run flutter pub get first")


def entry(source: str, locale: str) -> str:
    """The `'<locale>': <value>` map entry, value brace/paren-matched."""
    match = re.search(rf"^  [\"']{re.escape(locale)}[\"']: ", source, re.MULTILINE)
    if not match:
        raise SystemExit(f"locale {locale} not found")
    start = match.end()
    depth = 0
    quote = None
    for i in range(start, len(source)):
        char = source[i]
        if quote:
            if char == "\\":
                continue
            if char == quote and source[i - 1] != "\\":
                quote = None
        elif char in "'\"":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
            if depth == 0:
                return source[start : i + 1]
    raise SystemExit(f"unbalanced entry for {locale}")


def main() -> None:
    lib, version = intl_lib()
    symbols = (lib / "date_symbol_data_local.dart").read_text()
    patterns = (lib / "date_time_patterns.dart").read_text()

    def dart(value: str) -> str:
        # Match the app's lints: no `new`, single quotes where it's safe.
        value = value.replace("new DateSymbols(", "DateSymbols(")
        return re.sub(r'"([^"\'\\]*)"', r"'\1'", value)

    symbol_entries = "\n".join(
        f"  '{locale}': {dart(entry(symbols, locale))}," for locale in LOCALES
    )
    # The map below is const already, so its values drop their own const.
    pattern_entries = "\n".join(
        f"  '{locale}': {dart(entry(patterns, locale)).removeprefix('const ')},"
        for locale in LOCALES
    )
    OUT.write_text(
        f"""// GENERATED by tool/gen_date_symbols.py from intl {version} — do not
// edit; re-run the script after upgrading intl.
// ignore_for_file: lines_longer_than_80_chars

import 'package:intl/date_symbol_data_custom.dart';
import 'package:intl/date_symbols.dart';

/// Registers intl date formatting data for the app's languages only
/// ({', '.join(LOCALES)}), so DateFormat works in Bahasa even outside a
/// widget (notifications, the home widget). Replaces intl's
/// initializeDateFormatting(), which bundles every locale it knows — dead
/// weight in the web download.
void initializeAppDateFormatting() {{
  for (final MapEntry(key: locale, value: symbols) in _symbols.entries) {{
    initializeDateFormattingCustom(
      locale: locale,
      symbols: symbols,
      patterns: _patterns[locale],
    );
  }}
}}

final Map<String, DateSymbols> _symbols = {{
{symbol_entries}
}};

const Map<String, Map<String, String>> _patterns = {{
{pattern_entries}
}};
"""
    )
    print(f"wrote {OUT.relative_to(ROOT)} (intl {version})")


if __name__ == "__main__":
    main()
